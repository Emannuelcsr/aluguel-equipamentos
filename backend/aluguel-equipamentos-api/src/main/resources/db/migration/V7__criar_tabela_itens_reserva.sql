CREATE TABLE itens_reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reserva_id BIGINT NOT NULL,
    unidade_equipamento_id BIGINT NOT NULL,
    valor_diaria NUMERIC(10,2) NOT NULL,
    quantidade_dias BIGINT NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,

    CONSTRAINT pk_itens_reserva PRIMARY KEY (id),

    CONSTRAINT uk_itens_reserva_reserva_unidade
        UNIQUE (reserva_id, unidade_equipamento_id),

    CONSTRAINT fk_itens_reserva_reserva_id
        FOREIGN KEY (reserva_id)
        REFERENCES reservas(id),

    CONSTRAINT fk_itens_reserva_unidade_equipamento_id
        FOREIGN KEY (unidade_equipamento_id)
        REFERENCES unidades_equipamento(id)
);