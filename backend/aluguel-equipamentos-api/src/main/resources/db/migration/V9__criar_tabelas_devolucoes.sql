
CREATE TABLE devolucoes (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    reserva_id BIGINT NOT NULL,

    usuario_responsavel_id BIGINT NOT NULL,

    data_hora_devolucao TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_devolucoes
        PRIMARY KEY (id),

    CONSTRAINT fk_devolucoes_reserva_id
        FOREIGN KEY (reserva_id)
        REFERENCES reservas(id),

    CONSTRAINT fk_devolucoes_usuario_responsavel_id
        FOREIGN KEY (usuario_responsavel_id)
        REFERENCES usuarios(id),

    CONSTRAINT uk_devolucoes_reserva_id
        UNIQUE (reserva_id)

);


CREATE TABLE itens_devolucao (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    devolucao_id BIGINT NOT NULL,

    item_reserva_id BIGINT NOT NULL,

    condicao_fisica VARCHAR(30) NOT NULL,

    observacoes VARCHAR(500),

    CONSTRAINT pk_itens_devolucao
        PRIMARY KEY (id),

    CONSTRAINT fk_itens_devolucao_devolucao_id
        FOREIGN KEY (devolucao_id)
        REFERENCES devolucoes(id),

    CONSTRAINT fk_itens_devolucao_item_reserva_id
        FOREIGN KEY (item_reserva_id)
        REFERENCES itens_reserva(id),

    CONSTRAINT uk_itens_devolucao_item_reserva_id
        UNIQUE (item_reserva_id),

    CONSTRAINT ck_itens_devolucao_condicao_fisica
        CHECK (
            condicao_fisica IN (
                'SEM_DANOS_APARENTES',
                'COM_OBSERVACOES'
            )
        ),

    CONSTRAINT ck_itens_devolucao_observacoes
        CHECK (
            condicao_fisica <> 'COM_OBSERVACOES'
            OR (
                observacoes IS NOT NULL
                AND LENGTH(TRIM(observacoes)) > 0
            )
        )

);
