CREATE TABLE retiradas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reserva_id BIGINT NOT NULL,
    usuario_responsavel_id BIGINT NOT NULL,
    data_hora_retirada TIMESTAMPTZ NOT NULL,
    nome_recebedor VARCHAR(150) NOT NULL,
    documento_recebedor VARCHAR(11) NOT NULL,
    metodo_verificacao VARCHAR(30) NOT NULL,
    descricao_outro_metodo VARCHAR(500),
    
    CONSTRAINT pk_retiradas PRIMARY KEY (id),
	
	CONSTRAINT fk_retiradas_reserva_id FOREIGN KEY (reserva_id) REFERENCES reservas(id),

	CONSTRAINT fk_retiradas_usuario_responsavel_id FOREIGN KEY (usuario_responsavel_id) REFERENCES usuarios(id),
	
	CONSTRAINT uk_retiradas_reserva_id UNIQUE (reserva_id),
	
	CONSTRAINT ck_retiradas_metodo_verificacao
    CHECK (metodo_verificacao IN (
        'PRESENCIAL', 'TELEFONE', 'POR_ESCRITO', 'OUTRO'
    )),
    
    CONSTRAINT ck_retiradas_descricao_outro_metodo
    CHECK (
        metodo_verificacao <> 'OUTRO'
        OR (
            descricao_outro_metodo IS NOT NULL
            AND LENGTH(TRIM(descricao_outro_metodo)) > 0
        )
    )
	

);


CREATE TABLE itens_retirada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    retirada_id BIGINT NOT NULL,
    item_reserva_id BIGINT NOT NULL,
    condicao_fisica VARCHAR(30) NOT NULL,
    observacoes VARCHAR(500),
    
    CONSTRAINT pk_itens_retirada PRIMARY KEY (id),
	
	CONSTRAINT fk_itens_retirada_retirada_id FOREIGN KEY (retirada_id) REFERENCES retiradas(id),

	CONSTRAINT fk_itens_retirada_item_reserva_id FOREIGN KEY (item_reserva_id) REFERENCES itens_reserva(id),
	
	CONSTRAINT uk_itens_retirada_item_reserva_id UNIQUE (item_reserva_id),
	
	CONSTRAINT ck_itens_retirada_condicao_fisica
    CHECK (condicao_fisica IN (
        'SEM_DANOS_APARENTES', 'COM_OBSERVACOES'
    )),
    
    CONSTRAINT ck_itens_retirada_observacoes
	CHECK (
    condicao_fisica <> 'COM_OBSERVACOES'
    OR (
        observacoes IS NOT NULL
        AND LENGTH(TRIM(observacoes)) > 0
    )
)
	

);
